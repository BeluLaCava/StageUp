CREATE PROCEDURE dbo.sp_Traduccion_ListarDiccionario
    @idIdioma INT
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        e.claveEtiqueta,
        e.textoPredeterminado,
        COALESCE(NULLIF(t.textoTraducido, N''), e.textoPredeterminado) AS textoTraducido,
        e.modulo
    FROM dbo.EtiquetaTraduccion e
    LEFT JOIN dbo.Traduccion t
        ON t.idEtiquetaTraduccion = e.idEtiquetaTraduccion
       AND t.idIdioma = @idIdioma
    WHERE e.activo = 1
    ORDER BY e.modulo, e.textoPredeterminado;
END
GO

SELECT
    i.idIdioma,
    i.codigoIdioma,
    i.nombreIdioma,
    COUNT(e.idEtiquetaTraduccion) AS etiquetasActivas,
    SUM(CASE WHEN NULLIF(t.textoTraducido, N'') IS NOT NULL THEN 1 ELSE 0 END) AS traduccionesCargadas
FROM dbo.Idioma i
CROSS JOIN dbo.EtiquetaTraduccion e
LEFT JOIN dbo.Traduccion t
    ON t.idIdioma = i.idIdioma
   AND t.idEtiquetaTraduccion = e.idEtiquetaTraduccion
WHERE i.activo = 1
  AND e.activo = 1
GROUP BY
    i.idIdioma,
    i.codigoIdioma,
    i.nombreIdioma
ORDER BY i.idIdioma;
